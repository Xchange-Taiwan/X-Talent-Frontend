import fs from 'fs';
import path from 'path';

// Source: Ministry of Education 大專校院名錄 open data (Government Open Data
// License v1). Re-download from
// https://stats.moe.gov.tw/files/opendata/u1_new.json and overwrite this file
// whenever MOE publishes a new academic year, then re-run `pnpm generate:schools`.
const RAW_DATA_PATH = path.resolve(
  'scripts/data/moe-university-directory.json'
);
const OUTPUT_PATH = path.resolve(
  'src/components/profile/edit/educationSection/schoolData.ts'
);

export function normalizeTS(str) {
  return str.replace(/\r\n/g, '\n').trim();
}

// The dataset spans many academic years (each school reappears once per
// year, and a renamed/closed school shows up under multiple names across
// years) — only the latest year reflects which schools currently exist and
// what they're currently called.
export function extractLatestYearSchools(records) {
  const years = records.map((r) => Number(r['學年度']));
  const latestYear = Math.max(...years);

  const names = records
    .filter((r) => Number(r['學年度']) === latestYear)
    .map((r) => r['學校名稱']);

  const uniqueNames = Array.from(new Set(names));
  uniqueNames.sort((a, b) => a.localeCompare(b, 'zh-Hant'));

  return { latestYear, schools: uniqueNames };
}

export function generateSchoolDataTS(records) {
  const { latestYear, schools } = extractLatestYearSchools(records);

  const lines = [
    '// This file is automatically generated by scripts/generate-school-list.mjs',
    '// from scripts/data/moe-university-directory.json. Do not edit directly —',
    `// re-download the source data and run \`pnpm generate:schools\` instead.`,
    '//',
    '// Source: Ministry of Education 大專校院名錄 open data',
    '// (https://stats.moe.gov.tw/files/opendata/u1_new.json), Government Open',
    `// Data License v1. Reflects the ${latestYear} academic year.`,
    'export const taiwanSchools = [',
    // Single-quoted to match this repo's Prettier config (singleQuote: true)
    // so the committed output is stable under the pre-commit formatter.
    ...schools.map((school) => `  '${school.replace(/'/g, "\\'")}',`),
    '];',
    '',
  ];

  return lines.join('\n');
}

function loadRecords() {
  if (!fs.existsSync(RAW_DATA_PATH)) {
    console.error(`Error: source data not found at ${RAW_DATA_PATH}`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(RAW_DATA_PATH, 'utf8'));
}

function main() {
  const isCheckMode = process.argv.includes('--check');
  const records = loadRecords();
  const generatedTS = generateSchoolDataTS(records);

  if (isCheckMode) {
    if (!fs.existsSync(OUTPUT_PATH)) {
      console.error(`Error: generated file not found at ${OUTPUT_PATH}`);
      console.error(
        "Please run 'pnpm generate:schools' locally and commit the result."
      );
      process.exit(1);
    }

    const existingTS = fs.readFileSync(OUTPUT_PATH, 'utf8');

    if (normalizeTS(existingTS) !== normalizeTS(generatedTS)) {
      console.error(
        '========================================================================'
      );
      console.error('Error: school list drift detected.');
      console.error(`The committed file '${OUTPUT_PATH}'`);
      console.error(
        `does not match the latest source 'scripts/data/moe-university-directory.json'.`
      );
      console.error(
        "Please run 'pnpm generate:schools' locally and commit the result."
      );
      console.error(
        '========================================================================'
      );
      process.exit(1);
    }

    console.log('School list check passed. No drift detected.');
    process.exit(0);
  } else {
    fs.writeFileSync(OUTPUT_PATH, generatedTS, 'utf8');
    console.log(`Successfully generated school list at ${OUTPUT_PATH}`);
    process.exit(0);
  }
}

if (typeof process !== 'undefined' && !process.env.VITEST) {
  main();
}
